/* =====================================================
   SIMPLE HASH
===================================================== */

function hashPassword(password) {

    let hash = 2166136261;

    for (
        let i = 0;
        i < password.length;
        i++
    ) {

        hash ^= password.charCodeAt(i);

        hash =
            Math.imul(
                hash,
                16777619
            );

    }

    return (
        hash >>> 0
    ).toString(16);

}



/* =====================================================
   REGISTER
===================================================== */

function register() {

    const name =
        document
            .getElementById(
                "registerName"
            )
            .value
            .trim();

    const username =
        document
            .getElementById(
                "registerUsername"
            )
            .value
            .trim()
            .toLowerCase();

    const password =
        document
            .getElementById(
                "registerPassword"
            )
            .value;


    if (
        name.length < 2 ||
        username.length < 3 ||
        password.length < 6
    ) {

        alert(
            "Nama, username atau password belum memenuhi syarat."
        );

        return;

    }


    if (
        database.users.some(
            user =>
                user.username === username
        )
    ) {

        alert(
            "Username sudah digunakan."
        );

        return;

    }


    currentUser = {

        id:
            Date.now().toString(),

        name,

        username,

        password:
            hashPassword(password),

        highestLevel: 1,

        score: 0

    };


    database.users.push(
        currentUser
    );

    database.session =
        username;


    saveDatabase();

    startGame();

}



/* =====================================================
   LOGIN
===================================================== */

function login() {

    const username =
        document
            .getElementById(
                "loginUsername"
            )
            .value
            .trim()
            .toLowerCase();

    const password =
        document
            .getElementById(
                "loginPassword"
            )
            .value;


    const user =
        database.users.find(

            item =>

                item.username ===
                    username &&

                item.password ===
                    hashPassword(
                        password
                    )

        );


    if (!user) {

        alert(
            "Username atau password salah."
        );

        return;

    }


    currentUser = user;

    database.session =
        username;

    saveDatabase();

    startGame();

}



