/* =====================================================
   CANVAS RESPONSIVE
===================================================== */

function resizeCanvas() {

    canvas.width =
        COLS * TILE;

    canvas.height =
        ROWS * TILE;


    const container =
        document.getElementById(
            "gameContainer"
        );


    const ratio =
        Math.min(

            container.clientWidth /
                canvas.width,

            container.clientHeight /
                canvas.height

        );


    canvas.style.width =
        canvas.width *
        ratio +
        "px";


    canvas.style.height =
        canvas.height *
        ratio +
        "px";

}


window.addEventListener(
    "resize",
    resizeCanvas
);



/* =====================================================
   COLLISION
===================================================== */

function blocked(x, y) {

    return world.walls.some(

        wall =>
            wall.x === x &&
            wall.y === y

    );

}



/* =====================================================
   MOVE
===================================================== */

function move(dx, dy) {

    if (!world)
        return;


    let nx =
        world.player.x + dx;

    let ny =
        world.player.y + dy;


    if (
        nx < 1 ||
        ny < 1 ||
        nx >= COLS - 1 ||
        ny >= ROWS - 1
    ) {

        return;

    }


    if (
        blocked(nx, ny)
    ) {

        return;

    }


    world.player.x = nx;

    world.player.y = ny;


    collectCode();

    checkBug();

    checkGoal();


    draw();

}



/* =====================================================
   CODE
===================================================== */

function collectCode() {

    const index =
        world.codes.findIndex(

            item =>
                item.x ===
                    world.player.x &&
                item.y ===
                    world.player.y

        );


    if (index === -1)
        return;


    world.codes.splice(
        index,
        1
    );


    codeCollected++;

    totalScore += 25;


    document
        .getElementById(
            "codes"
        )
        .textContent =
            codeCollected;


    document
        .getElementById(
            "score"
        )
        .textContent =
            totalScore;

}



/* =====================================================
   BUG
===================================================== */

function checkBug() {

    const hit =
        world.bugs.some(

            bug =>
                bug.x ===
                    world.player.x &&
                bug.y ===
                    world.player.y

        );


    if (!hit)
        return;


    lives--;


    document
        .getElementById(
            "lives"
        )
        .textContent =
            lives;


    if (lives <= 0) {

        alert(
            "🐛 Bug menyerang! Level diulang."
        );

        startLevel();

    }

}



/* =====================================================
   GOAL
===================================================== */

function checkGoal() {

    if (

        world.player.x ===
            world.goal.x &&

        world.player.y ===
            world.goal.y

    ) {

        setTimeout(
            startQuiz,
            250
        );

    }

}



/* =====================================================
   DRAW GAME
===================================================== */

function draw() {

    resizeCanvas();


    ctx.fillStyle =
        "#06101b";

    ctx.fillRect(
        0,
        0,
        canvas.width,
        canvas.height
    );


    /* FLOOR */

    for (
        let y = 0;
        y < ROWS;
        y++
    ) {

        for (
            let x = 0;
            x < COLS;
            x++
        ) {

            ctx.fillStyle =
                (x + y) % 2
                    ? "#0b1c2c"
                    : "#0d2235";


            ctx.fillRect(

                x * TILE,

                y * TILE,

                TILE - 1,

                TILE - 1

            );

        }

    }


    /* WALL */

    world.walls.forEach(
        wall => {

            ctx.fillStyle =
                "#172e46";

            ctx.fillRect(

                wall.x * TILE + 2,

                wall.y * TILE + 2,

                TILE - 4,

                TILE - 4

            );

        }
    );


    ctx.textAlign =
        "center";


    /* CODE */

    world.codes.forEach(
        item => {

            ctx.font =
                "24px Arial";

            ctx.fillText(

                "💻",

                item.x * TILE + 16,

                item.y * TILE + 25

            );

        }
    );


    /* BUG */

    world.bugs.forEach(
        bug => {

            ctx.font =
                "23px Arial";

            ctx.fillText(

                "🐛",

                bug.x * TILE + 16,

                bug.y * TILE + 25

            );

        }
    );


    /* GOAL */

    ctx.font =
        "25px Arial";

    ctx.fillText(

        "🏁",

        world.goal.x * TILE + 16,

        world.goal.y * TILE + 25

    );


    /* PLAYER */

    ctx.fillText(

        "🤖",

        world.player.x * TILE + 16,

        world.player.y * TILE + 25

    );

}



/* =====================================================
   KEYBOARD
===================================================== */

window.addEventListener(
    "keydown",
    event => {

        const keys = {

            ArrowUp: [0, -1],

            ArrowDown: [0, 1],

            ArrowLeft: [-1, 0],

            ArrowRight: [1, 0],

            w: [0, -1],

            W: [0, -1],

            s: [0, 1],

            S: [0, 1],

            a: [-1, 0],

            A: [-1, 0],

            d: [1, 0],

            D: [1, 0]

        };


        if (
            keys[event.key]
        ) {

            event.preventDefault();

            move(
                keys[event.key][0],
                keys[event.key][1]
            );

        }

    }
);



