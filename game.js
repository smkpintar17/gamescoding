/* =====================================================
   WALLS
===================================================== */

function createWalls() {

    world.walls = [];


    for (
        let y = 0;
        y < ROWS;
        y++
    ) {

        for (
            let x = 0;
            x < COLS;
            x++
        ) {

            if (
                x === 0 ||
                y === 0 ||
                x === COLS - 1 ||
                y === ROWS - 1
            ) {

                world.walls.push({
                    x,
                    y
                });

            }

        }

    }


    for (
        let y = 2;
        y < ROWS - 2;
        y += 2
    ) {

        for (
            let x = 2;
            x < COLS - 2;
            x++
        ) {

            if (
                (x + y + currentLevel) %
                4 !== 0
            ) {

                world.walls.push({
                    x,
                    y
                });

            }

        }

    }


    /* Safe route */

    world.walls =
        world.walls.filter(
            wall =>
                wall.y !== ROWS - 2 &&
                wall.x !== COLS - 2
        );

}



