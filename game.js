/* =====================================================
   LOAD
===================================================== */

function loadDatabase() {

    try {

        const saved =
            localStorage.getItem(
                STORAGE_KEY
            );

        if (saved) {

            database =
                JSON.parse(saved);

        }

    }

    catch (error) {

        console.log(error);

    }

}


function saveDatabase() {

    localStorage.setItem(

        STORAGE_KEY,

        JSON.stringify(database)

    );

}



